test('accepts the sign-off that Dependabot adds to every commit it makes', () => {
	assert.deepEqual(findViolations(DEPENDABOT_MESSAGE), []);
});

for (const signOff of [
	'Signed-off-by: dependabot[bot] <someone@example.com>',
	'Signed-off-by: dependabot <support@github.com>',
	'Signed-off-by: Claude <noreply@anthropic.com>',
	'Signed-off-by: dependabot[bot] <support@github.com> and Claude',
]) {
	test(`rejects the sign-off ${JSON.stringify(signOff)}, which is not Dependabot's exact line`, () => {
		assert.deepEqual(findViolations(`${clean}\n${signOff}\n`), [
			{ line: 5, rule: 'attribution trailer', text: signOff },
		]);
	});
}

test('comment lines and the diff below the scissors line are ignored, as git drops them', () => {
	const message = [
		clean,
		'# 🤖 Generated with [Claude Code](https://claude.com/claude-code)',
		'# ------------------------ >8 ------------------------',
		'+Co-Authored-By: inside a diff',
		' Co-Authored-By: diff context',
		'Generated with Claude Code',
	].join('\n');
	assert.deepEqual(findViolations(message), []);
});

test('the last line is checked when the message has no final newline', () => {
	assert.deepEqual(findViolations('fix: x\n\nCo-Authored-By: X <x@y.z>'), [
		{ line: 3, rule: 'attribution trailer', text: 'Co-Authored-By: X <x@y.z>' },
	]);
});

test('a message with CRLF line endings reports clean lines and honours the scissors line', () => {
	assert.deepEqual(findViolations('fix: x\r\n\r\nCo-Authored-By: X <x@y.z>\r\n'), [
		{ line: 3, rule: 'attribution trailer', text: 'Co-Authored-By: X <x@y.z>' },
	]);
	const verbose = 'fix: x\r\n# ------------------------ >8 ------------------------\r\n Co-Authored-By: diff\r\n';
	assert.deepEqual(findViolations(verbose), []);
});

test('runForbidTrailers returns 1, names each forbidden line and says how to fix it, 0 for a clean message', () => {
	/** @type {string[]} */
	const lines = [];
	const file = messageFile(`${clean}\nCo-Authored-By: Claude <noreply@anthropic.com>\n`);
	assert.equal(runForbidTrailers({ file, log: (line) => lines.push(line) }), 1);
	assert.deepEqual(lines, [
		'line 5: attribution trailer: Co-Authored-By: Claude <noreply@anthropic.com>',
		'Remove these lines. Commits here have one author and no AI attribution.',
	]);
	assert.equal(runForbidTrailers({ file: messageFile(clean), log: silent }), 0);
});

test('runForbidTrailers prints usage and returns 1 without a file argument', () => {
	/** @type {string[]} */
	const lines = [];
	assert.equal(runForbidTrailers({ file: undefined, log: (line) => lines.push(line) }), 1);
	assert.match(lines.join('\n'), /usage: node scripts\/forbid-trailers\.mjs <commit-msg-file>/);
});

test('runForbidTrailers reports on stderr by default', (t) => {
	const write = t.mock.method(process.stderr, 'write', () => true);
	const code = runForbidTrailers({ file: messageFile('Generated with Claude Code\n') });
	write.mock.restore();
	assert.equal(code, 1);
	assert.match(String(write.mock.calls[0]?.arguments[0]), /^line 1: AI attribution: Generated with Claude Code\n$/);
});

test('the CLI that the commit-msg hook runs exits 1 on a forbidden line and 0 on a clean message', () => {
	const cli = fileURLToPath(new URL('./forbid-trailers.mjs', import.meta.url));
	const bad = spawnSync(process.execPath, [cli, messageFile(`${clean}\nCo-Authored-By: X <x@y.z>\n`)], {
		encoding: 'utf8',
	});
	assert.equal(bad.status, 1);
	assert.match(bad.stderr, /attribution trailer/);
	assert.equal(spawnSync(process.execPath, [cli, messageFile(clean)]).status, 0);
});
