test('a conventional message with a Why body has no violations', () => {
	assert.deepEqual(findViolations(clean), []);
});

for (const trailer of TRAILERS) {
	test(`rejects the trailer ${JSON.stringify(trailer)} with its line number`, () => {
		assert.deepEqual(findViolations(`${clean}\n${trailer}\n`), [
			{ line: 5, rule: 'attribution trailer', text: trailer },
		]);
	});
}

